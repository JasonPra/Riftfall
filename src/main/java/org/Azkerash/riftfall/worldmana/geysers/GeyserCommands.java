package org.Azkerash.riftfall.worldmana.geysers;

import java.util.Locale;
import net.minecraft.commands.Commands;
import net.minecraft.core.BlockPos;
import net.minecraft.network.chat.Component;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.neoforge.event.RegisterCommandsEvent;

/** Operator geyser commands. Only teleport generates destination terrain. */
public final class GeyserCommands {
    @SubscribeEvent public static void register(RegisterCommandsEvent event){
        event.getDispatcher().register(Commands.literal("riftfall").requires(s->s.hasPermission(2)).then(Commands.literal("geyser")
            .then(Commands.literal("inspect").executes(c->{
                var source=c.getSource();var field=GeyserQueries.at(source.getLevel(),BlockPos.containing(source.getPosition()));
                if(field.isEmpty()){source.sendSuccess(()->Component.literal("This chunk is outside a mana geyser."),false);return 0;}
                var g=field.orElseThrow();int x=BlockPos.containing(source.getPosition()).getX()>>4,z=BlockPos.containing(source.getPosition()).getZ()>>4;
                source.sendSuccess(()->Component.literal(String.format(Locale.ROOT,"Geyser center %.0f, %.0f; %dx%d chunk-equivalent area (%d blocks across before boundary noise), full world height; shared capacity %.0f; collective %.2f mana/tick; zone: %s; crystal caves: %s",g.centerX(),g.centerZ(),g.width(),g.width(),g.circular()?(int)Math.round(GeyserShape.radius(g)*2):g.blockWidth(),GeyserLedger.capacity(g),GeyserLedger.regeneration(g),g.legacy()&&g.zone(x,z)==GeyserZone.CORE?"reserved legacy center":g.zone(x,z).title(),g.crystalZone(x,z)?"yes":"no")),false);return 1;
            }))
            .then(Commands.literal("locate").executes(c->{
                var source=c.getSource();var best=nearest(source);
                if(best==null){source.sendFailure(Component.literal("No geyser candidate found in the search area."));return 0;}
                var found=best;source.sendSuccess(()->Component.literal("Geyser candidate at X="+(int)found.centerX()+", Z="+(int)found.centerZ()+" ("+found.width()+"x"+found.width()+" chunks; "+(found.legacy()?"preserved legacy field":"ecosystem field")+"). Terrain was not generated by this search."),false);return 1;
            }))
            .then(Commands.literal("teleport").executes(c->{
                var source=c.getSource();var player=source.getPlayerOrException();var field=randomUnvisited(source);
                if(field==null){source.sendFailure(Component.literal("No undiscovered geyser found in the search area. Try again."));return 0;}
                var level=source.getLevel();var destination=arrival(level,field);
                GeyserRegions.get(level).discover(field.centerChunkX(),field.centerChunkZ());
                player.stopRiding();
                player.teleportTo(level,destination.getX()+.5,destination.getY(),destination.getZ()+.5,player.getYRot(),player.getXRot());
                player.fallDistance=0;
                source.sendSuccess(()->Component.literal("Teleported to a new random geyser at "+destination.getX()+", "+destination.getY()+", "+destination.getZ()+"."),true);
                return 1;
            }))));
    }
    private static GeyserRegion randomUnvisited(net.minecraft.commands.CommandSourceStack source){
        var level=source.getLevel();var regions=GeyserRegions.get(level);
        var seen=new java.util.HashSet<>(regions.discovered());
        int cx=Math.floorDiv(net.minecraft.util.Mth.floor(source.getPosition().x)>>4,GeyserLayout.CELL_CHUNKS);
        int cz=Math.floorDiv(net.minecraft.util.Mth.floor(source.getPosition().z)>>4,GeyserLayout.CELL_CHUNKS);
        for(int attempt=0;attempt<256;attempt++){
            int dx=level.random.nextInt(129)-64,dz=level.random.nextInt(129)-64;
            if(Math.max(Math.abs(dx),Math.abs(dz))<16)continue;
            var candidate=regions.candidate(cx+dx,cz+dz);if(candidate.isEmpty())continue;
            var field=candidate.orElseThrow();
            if(seen.contains(field)||field.contains(net.minecraft.util.Mth.floor(source.getPosition().x)>>4,net.minecraft.util.Mth.floor(source.getPosition().z)>>4))continue;
            if(!level.getWorldBorder().isWithinBounds(new BlockPos((int)field.centerX(),0,(int)field.centerZ())))continue;
            return field;
        }
        return null;
    }
    /** Metadata-only nearest search for locate. */
    private static GeyserRegion nearest(net.minecraft.commands.CommandSourceStack source){
        var regions=GeyserRegions.get(source.getLevel());
        int x=BlockPos.containing(source.getPosition()).getX()>>4,z=BlockPos.containing(source.getPosition()).getZ()>>4;
        int cx=Math.floorDiv(x,GeyserLayout.CELL_CHUNKS),cz=Math.floorDiv(z,GeyserLayout.CELL_CHUNKS);
        GeyserRegion best=null;double distance=Double.POSITIVE_INFINITY;
        for(var saved:regions.discovered()){
            double d=Math.hypot(saved.centerX()-source.getPosition().x,saved.centerZ()-source.getPosition().z);
            if(d<distance){best=saved;distance=d;}
        }
        for(int dx=-8;dx<=8;dx++)for(int dz=-8;dz<=8;dz++){
            var candidate=regions.candidate(cx+dx,cz+dz);if(candidate.isEmpty())continue;var g=candidate.orElseThrow();double d=Math.hypot(g.centerX()-source.getPosition().x,g.centerZ()-source.getPosition().z);
            if(d<distance){best=g;distance=d;}
        }
        return best;
    }
    /** Development arrival above the center's canopy/water; no landing-safety filtering. */
    private static BlockPos arrival(net.minecraft.server.level.ServerLevel level,GeyserRegion field){
        int x=(int)field.centerX(),z=(int)field.centerZ();
        var chunk=level.getChunk(field.centerChunkX(),field.centerChunkZ());
        int y=net.minecraft.util.Mth.clamp(chunk.getHeight(net.minecraft.world.level.levelgen.Heightmap.Types.WORLD_SURFACE,x&15,z&15)+3,
            level.getMinBuildHeight()+1,level.getMaxBuildHeight()-1);
        return new BlockPos(x,y,z);
    }
    private GeyserCommands(){}
}
